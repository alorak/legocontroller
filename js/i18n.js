let currentLang = localStorage.getItem('deviceController.lang') || 'en';

function t(key, params){
  const str = (I18N[currentLang] && I18N[currentLang][key]) ||
              (I18N.en && I18N.en[key]) || key;
  if(!params) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => params[k] !== undefined ? params[k] : `{${k}}`);
}

function metricLabel(key, fallback){
  const k = 'm_' + key;
  const val = t(k);
  return val !== k ? val : (fallback || key);
}

function setLang(lang){
  currentLang = (lang === 'tr' || lang === 'en') ? lang : 'en';
  try { localStorage.setItem('deviceController.lang', currentLang); } catch(e){}
  updateLangUI();
}

function updateLangUI(){
  document.documentElement.lang = currentLang;
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if(k) el.innerHTML = t(k);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const k = el.dataset.i18nPh;
    if(k) el.placeholder = t(k);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const k = el.dataset.i18nTitle;
    if(k) el.title = t(k);
  });
  buildPicker();
  devices.forEach(d => {
    if(d.typeInfo){
      if(isHubType(d.type)){
        const oldCard = d.el;
        if(oldCard){
          const meta = oldCard.querySelector('.meta');
          if(meta) meta.innerHTML = `<span class="dot"></span><span class="state">${d.stateText ? d.stateText(d) : t('waiting')}</span> · ${deviceTypeLabel(d.typeInfo)}`;
          setText(oldCard, '[data-act=disconnect]', t('disconnect'));
          setText(oldCard, '[data-raw]', t('rawPacketLog'));
          setText(oldCard, '[data-act=reconnect]', t('btnReconnect'));
          setDeviceConnectedUI(d, !!(d.device && d.device.gatt && d.device.gatt.connected));
        }
        (d.slotEls || []).forEach(card => {
          if(card){
            card.dataset.built = '';
            const crumb = card.querySelector('[data-crumb]');
            if(crumb) crumb.title = t('backToHub');
          }
        });
        renderHubSlots(d);
      }else{
        renderCard(d, d.typeInfo, d.el);
        renderListItem(d, d.typeInfo, d.item);
      }
      paint(d);
    }
  });
  if(selectedId) selectTarget(selectedId);
  renderPanoTabs();
  if(currentView === 'pano') renderPano(); else paintPano();
}
